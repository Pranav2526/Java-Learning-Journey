class WhileLoop
{
    public static void main(String a[])
    {
        // While Loop
        int i = 1;

        while(i<=10)
        {
            System.out.println(i + " Hi, My name is Pranav");
            i++;
        }


        // Do-While Loop
        int j = 5;

        do
        {
            System.out.println("Hi, My name is Pranav");
            j++;
        } while(j<=4);
    }
}